// ABOUTME: Генерирует публичные объявления TypeScript из схем agent и Codex.
// ABOUTME: Записывает только contracts/index.d.mts; runtime не читает файлы.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import ts from 'typescript';

const here=dirname(fileURLToPath(import.meta.url));
const schemaPath=resolve(here,'../schemas/messages.schema.json');
const codexPath=resolve(here,'../contracts/codex/schema.json');
const outputPath=resolve(here,'../contracts/index.d.mts');
const own=JSON.parse(await readFile(schemaPath,'utf8'));
const codex=JSON.parse(await readFile(codexPath,'utf8'));
const upstreamTypes=new Set();
const ownForTypes=structuredClone(own);
const replaceRefs=value=>{
  if(!value||typeof value!=='object')return;
  for(const [key,child] of Object.entries(value)){
    if(key==='$ref'&&typeof child==='string'&&child.startsWith('https://brai.dev/contracts/codex/schema.json#/definitions/')){
      const name=child.split('/').at(-1); upstreamTypes.add(name); value.tsType=`Codex${name}`; delete value.$ref;
    }else replaceRefs(child);
  }
};
replaceRefs(ownForTypes.definitions);
const blocks=new Map();
const collect=rendered=>{
  const source=ts.createSourceFile('generated.d.ts',rendered,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
  for(const statement of source.statements){
    if(!ts.isInterfaceDeclaration(statement)&&!ts.isTypeAliasDeclaration(statement))continue;
    const name=statement.name.text,block=rendered.slice(statement.getStart(source),statement.end);
    const prior=blocks.get(name);
    if(prior&&prior!==block)throw new Error(`Конфликт сгенерированного типа ${name}`);
    blocks.set(name,block);
  }
};
const ownRoots=Object.keys(own.definitions).filter(name=>name.endsWith('Request')||name.endsWith('Response')||['ThreadSnapshot','PendingRequest','EventEnvelope','HistoryItem','Trace','Project','ThreadMetadata','Truncation'].includes(name));
const references=(value,into=[])=>{if(!value||typeof value!=='object')return into;for(const [key,child] of Object.entries(value)){if(key==='$ref'&&typeof child==='string')into.push(child);else references(child,into);}return into;};
const inline=(value,definitions,seen=new Set())=>{if(Array.isArray(value))return value.map(child=>inline(child,definitions,seen));if(!value||typeof value!=='object')return value;if(typeof value.$ref==='string'&&value.$ref.startsWith('#/definitions/')){const name=value.$ref.slice('#/definitions/'.length);if(seen.has(name))return {type:'object',additionalProperties:true};return inline(definitions[name],definitions,new Set([...seen,name]));}const copy={};for(const [key,child]of Object.entries(value))if(key!=='definitions')copy[key]=inline(child,definitions,seen);return copy;};
for(const name of ownRoots){
  const definition=ownForTypes.definitions[name];
  const root={...inline(definition,ownForTypes.definitions),$schema:own.$schema,title:name};
  try { collect(await compile(root,name,{bannerComment:''})); } catch(error) { throw new Error(`Генерация ${name}: ${error.message}`); }
}
const upstreamDefinitions=structuredClone(codex.definitions);
const prefixRefs=value=>{
  if(!value||typeof value!=='object')return;
  for(const [key,child] of Object.entries(value)){
    if(key==='$ref'&&typeof child==='string'&&child.startsWith('#/definitions/'))value[key]=`#/definitions/Codex${child.split('/').at(-1)}`;
    else prefixRefs(child);
  }
};
const prefixed={};
for(const [name,definition] of Object.entries(upstreamDefinitions)){const value=structuredClone(definition);prefixRefs(value);prefixed[`Codex${name}`]=value;}
for(const name of upstreamTypes){
  const root={...inline(prefixed[`Codex${name}`],prefixed),$schema:codex.$schema,title:`Codex${name}`};
  try { collect(await compile(root,`Codex${name}`,{bannerComment:''})); } catch(error) { throw new Error(`Генерация Codex${name}: ${error.message}`); }
}
let generated=[...blocks.values()].join('\n\n');
generated=generated.replace(/messages: \{[\s\S]*?\n  \}\[\];/g,'messages: AguiMessage[];').replace(/event: \{[\s\S]*?\n  \};/g,'event: AguiEvent;');
const dtoNames=Object.keys(own.definitions).filter(name=>name.endsWith('Request')||name.endsWith('Response')||['ThreadSnapshot','PendingRequest'].includes(name));
const declaration=`// Generated by scripts/generate-contract-types.mjs. Do not edit.\nimport type { Event as AguiEvent, Message as AguiMessage } from '@ag-ui/core';\n\n${generated}\n\nexport type DtoName=keyof DtoMap;\nexport interface DtoMap {\n${dtoNames.map(name=>`  ${name}: ${name};`).join('\n')}\n}\nexport declare const messagesSchema: typeof import('../schemas/messages.schema.json');\nexport declare const subjects: Readonly<Record<string,string>>;\nexport declare const limits: Readonly<Record<string,number>>;\nexport declare function validateDto<Name extends DtoName>(name:Name,value:unknown):value is DtoMap[Name];\nexport declare function assertDto<Name extends DtoName>(name:Name,value:unknown):asserts value is DtoMap[Name];\nexport declare function validateEventEnvelope(value:unknown):value is EventEnvelope;\nexport declare function validateAguiEvent(value:unknown):value is AguiEvent;\nexport type SupportedPendingRequest=Exclude<PendingRequest,{kind:'unsupported'}>;\nexport declare function validateUpstreamAnswer(kind:SupportedPendingRequest['kind'],answer:unknown,params:SupportedPendingRequest['params']):boolean;\nexport declare function serializedBytes(value:unknown):number;\n`;
if(process.argv.includes('--check')){const current=await readFile(outputPath,'utf8').catch(()=> '');if(current!==declaration){console.error(`${outputPath} устарел; выполните node services/agent/scripts/generate-contract-types.mjs`);process.exitCode=1;}}
else await writeFile(outputPath,declaration);
