// ABOUTME: Проверяет долговечную lifecycle очередь Auth с настоящими транзакциями PostgreSQL.
// ABOUTME: Допускает только синтетический стенд на 127.0.0.1:15459, не продуктовую БД.
import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { Pool } from "pg";
import { adminAction } from "../../dist/admin.js";
import { lifecycleWorker } from "../../dist/lifecycle.js";
import { profileReady } from "../../dist/identity.js";
import { issueCode } from "../../dist/login-code.js";
import { createAuth } from "../../dist/auth.js";
import { sessionIdentity } from "../../dist/v2.js";
import { validate } from "../../dist/schema.js";

function fixtureURL(name) {
 const value=process.env[name];if(!value)throw new Error("Explicit "+name+" required");
 const url=new URL(value);
 if(url.pathname!=="/brai_auth_test"||url.hostname!=="127.0.0.1"||url.port!=="15459")throw new Error("Refusing non-fixture database");
 return value;
}
const ownerURL=fixtureURL("AUTH_TEST_OWNER_URL"),appURL=fixtureURL("AUTH_TEST_APP_URL");
const owner=new Pool({connectionString:ownerURL}),app=new Pool({connectionString:appURL});
const secret="fixture-auth-secret-32-characters-long";
test("admin lifecycle serializes grants, revokes, leases and explicit retries",async()=>{
 const actor=randomUUID(),telegramId=String(Date.now())+"77";
 const action=(op,body)=>adminAction(app,secret,actor,op,body);
 const requestId=randomUUID();
 let userId;
 try {
  await promisify(execFile)(process.execPath,[new URL("../../dist/migrate.js",import.meta.url).pathname],{env:{...process.env,AUTH_DATABASE_URL:ownerURL,AUTH_OWNER_ROLE:"auth_owner",AUTH_APP_ROLE:"auth_app",AUTH_SECRET:secret,AUTH_ORIGIN:"https://fixture.example",AUTH_EMAIL_FROM:"Fixture <test@example.com>"},timeout:30000});
  await owner.query('INSERT INTO "user"(id,name,email,"emailVerified","createdAt","updatedAt") VALUES($1,$2,$3,false,now(),now())',[actor,"Fixture admin",actor+"@fixture.example"]);
  await owner.query("INSERT INTO brai_identity(user_id,telegram_id,profile_id,role,status) VALUES($1,$2,$3,'admin','active')",[actor,telegramId+"1",randomUUID()]);
  const grants=await Promise.all(Array.from({length:6},()=>action("users-add",{requestId,telegramId})));
  assert.ok(grants.every(r=>r.status===200));
  assert.equal(new Set(grants.map(r=>r.body.operation.id)).size,1);
  userId=grants[0].body.user.id;
  const profileId=grants[0].body.user.profileId;
  assert.match(userId,/^[0-9a-f-]{36}$/);assert.match(profileId,/^[0-9a-f-]{36}$/);
  assert.equal(grants[0].body.user.role,"user");assert.equal(grants[0].body.user.status,"provisioning");
  assert.equal((await action("users-add",{requestId,telegramId:telegramId+"9"})).body.code,"REQUEST_CONFLICT");
  const lookup=await action("users-operation-get",{requestId});
  assert.equal(lookup.body.operation.id,grants[0].body.operation.id);assert.equal(lookup.body.user.id,userId);
  assert.equal(await profileReady(app,userId,profileId),null);
  assert.equal(await issueCode(app,secret,telegramId),null);
  const claims=await Promise.all(Array.from({length:6},(_,i)=>lifecycleWorker(app,"claim",{workerId:"fixture-"+i})));
  assert.equal(claims.filter(r=>r.operation).length,1);
  const old=claims.find(r=>r.operation).operation;
  validate("LifecycleClaimResponse",{operation:old});
  assert.equal((await lifecycleWorker(app,"renew",{operationId:old.id,leaseToken:old.leaseToken})).accepted,true);
  assert.equal((await lifecycleWorker(app,"complete",{operationId:old.id,leaseToken:"wrong",success:true})).accepted,false);
  const revoke=await action("users-revoke",{requestId:randomUUID(),userId});
  assert.equal(revoke.body.user.status,"blocked");
  const replay=await action("users-add",{requestId,telegramId});
  assert.equal(replay.body.operation.id,old.id);assert.equal(replay.body.operation.state,"cancelled");assert.equal(replay.body.user.status,"blocked");
  assert.equal((await lifecycleWorker(app,"claim",{workerId:"busy"})).operation,null);
  assert.equal((await lifecycleWorker(app,"complete",{operationId:old.id,leaseToken:old.leaseToken,success:true})).accepted,false);
  assert.equal(await profileReady(app,userId,profileId),null);
  const stopped=(await lifecycleWorker(app,"claim",{workerId:"stop"})).operation;
  assert.equal(stopped.kind,"stop");
  assert.equal((await lifecycleWorker(app,"complete",{operationId:stopped.id,leaseToken:stopped.leaseToken,success:true})).accepted,true);
  await owner.query('UPDATE "user" SET name=$2 WHERE id=$1',[userId,"Preserved fixture"]);
  await action("role-set",{userId,role:"admin"});
  const restored=await action("users-add",{requestId:randomUUID(),telegramId});
  assert.equal(restored.body.user.id,userId);assert.equal(restored.body.user.profileId,profileId);assert.equal(restored.body.user.role,"admin");assert.equal(restored.body.user.name,"Preserved fixture");
  const failure=(await lifecycleWorker(app,"claim",{workerId:"failure"})).operation;
  const failed=await lifecycleWorker(app,"complete",{operationId:failure.id,leaseToken:failure.leaseToken,success:false,errorCode:"PROFILE_FAILED"});
  assert.equal(failed.operation.state,"failed");
  assert.equal((await lifecycleWorker(app,"claim",{workerId:"no-auto-retry"})).operation,null);
  assert.equal(await profileReady(app,userId,profileId),null);
  await action("users-add",{requestId:randomUUID(),telegramId});
  const expired=(await lifecycleWorker(app,"claim",{workerId:"expires"})).operation;
  await owner.query("UPDATE brai_user_operation SET lease_expires_at=now()-interval '1 second' WHERE id=$1",[expired.id]);
  const resumed=(await lifecycleWorker(app,"claim",{workerId:"recovers"})).operation;
  assert.equal(resumed.id,expired.id);assert.notEqual(resumed.leaseToken,expired.leaseToken);
  assert.equal((await lifecycleWorker(app,"complete",{operationId:expired.id,leaseToken:expired.leaseToken,success:true})).accepted,false);
  assert.equal((await lifecycleWorker(app,"complete",{operationId:resumed.id,leaseToken:resumed.leaseToken,success:true})).accepted,true);
  assert.equal((await profileReady(app,userId,profileId)).status,"active");
  const cfg={identityMode:"telegram",origin:"https://fixture.example",trustedOrigins:["https://fixture.example"],secret};
  const engine=createAuth(cfg,app);
  const login=async(code)=>engine.handler(new Request(cfg.origin+"/api/auth/brai/telegram-redeem",{method:"POST",headers:{origin:cfg.origin,"content-type":"application/json","x-forwarded-for":"192.0.2.77"},body:JSON.stringify({code})}));
  const loginCode=await issueCode(app,secret,telegramId);
  const signed=await login(loginCode.code);assert.equal(signed.status,200);
  const cookie=signed.headers.getSetCookie().map(v=>v.split(";")[0]).join("; ");
  const headers=new Headers({cookie});
  const live=await sessionIdentity(app,cfg,engine.handler,headers);assert.equal(live.id,userId);
  const epoch=(await owner.query("SELECT lifecycle_generation FROM brai_identity WHERE user_id=$1",[userId])).rows[0].lifecycle_generation;
  const staleId=randomUUID();
  await owner.query('INSERT INTO "session"(id,token,"userId","expiresAt","createdAt","updatedAt",brai_generation) VALUES($1,$2,$3,now()+interval \'1 hour\',now(),now(),$4)',[staleId,randomUUID(),userId,epoch-1]);
  assert.equal((await action("users-add",{requestId:randomUUID(),telegramId})).body.user.status,"active");
  assert.equal((await sessionIdentity(app,cfg,engine.handler,headers)).id,userId);
  assert.equal((await owner.query('SELECT brai_generation FROM "session" WHERE id=$1',[staleId])).rows[0].brai_generation,epoch-1);
  const staleHandler=async()=>Response.json({user:{id:userId},session:{id:staleId}});
  assert.equal(await sessionIdentity(app,cfg,staleHandler,new Headers()),null);
  // Детерминированно ставим revoke/restore между погашением кода и созданием сессии движка.
  const context=await engine.$context;
  const createSession=context.internalAdapter.createSession.bind(context.internalAdapter);
  context.internalAdapter.createSession=async(...args)=>{
   context.internalAdapter.createSession=createSession;
   await action("users-revoke",{requestId:randomUUID(),userId});
   const stop=(await lifecycleWorker(app,"claim",{workerId:"login-race-stop"})).operation;
   await lifecycleWorker(app,"complete",{operationId:stop.id,leaseToken:stop.leaseToken,success:true});
   await action("users-add",{requestId:randomUUID(),telegramId});
   const prepare=(await lifecycleWorker(app,"claim",{workerId:"login-race-restore"})).operation;
   await lifecycleWorker(app,"complete",{operationId:prepare.id,leaseToken:prepare.leaseToken,success:true});
   return createSession(...args);
  };
  const raceCode=await issueCode(app,secret,telegramId);
  const racedLogin=await login(raceCode.code);
  assert.equal(racedLogin.status,401);assert.equal(racedLogin.headers.get("set-cookie"),null);
  assert.equal((await owner.query('SELECT 1 FROM "session" WHERE "userId"=$1',[userId])).rowCount,0);
  assert.equal(await sessionIdentity(app,cfg,engine.handler,headers),null);
  assert.equal((await lifecycleWorker(app,"claim",{workerId:"noop"})).operation,null);
  const code=await issueCode(app,secret,telegramId);assert.ok(code);
  await owner.query('INSERT INTO "session"(id,token,"userId","expiresAt","createdAt","updatedAt") VALUES($1,$2,$3,now()+interval \'1 hour\',now(),now())',[randomUUID(),randomUUID(),userId]);
  await action("status-set",{requestId:randomUUID(),userId,status:"blocked"});
  assert.equal((await owner.query('SELECT 1 FROM "session" WHERE "userId"=$1',[userId])).rowCount,0);
  assert.equal((await owner.query('SELECT 1 FROM brai_login_code WHERE user_id=$1',[userId])).rowCount,0);
  const stop=(await lifecycleWorker(app,"claim",{workerId:"stop2"})).operation;
  await lifecycleWorker(app,"complete",{operationId:stop.id,leaseToken:stop.leaseToken,success:true});
  await action("status-set",{requestId:randomUUID(),userId,status:"provisioning"});
  const pending=(await lifecycleWorker(app,"claim",{workerId:"provisioning"})).operation;
  await lifecycleWorker(app,"complete",{operationId:pending.id,leaseToken:pending.leaseToken,success:true});
  assert.equal(await profileReady(app,userId,profileId),null);
  await action("status-set",{requestId:randomUUID(),userId,status:"active"});
  const active=(await lifecycleWorker(app,"claim",{workerId:"active"})).operation;
  await lifecycleWorker(app,"complete",{operationId:active.id,leaseToken:active.leaseToken,success:true});
  const raced=await Promise.all(Array.from({length:12},(_,i)=>i%2?action("users-add",{requestId:randomUUID(),telegramId}):action("users-revoke",{requestId:randomUUID(),userId})));
  assert.ok(raced.every(r=>r.status===200));
  const history=(await owner.query("SELECT generation,state FROM brai_user_operation WHERE user_id=$1 ORDER BY generation",[userId])).rows;
  assert.deepEqual(history.map(r=>r.generation),Array.from({length:history.length},(_,i)=>i+1));
  assert.equal(history.filter(r=>["pending","running"].includes(r.state)).length,1);
  const list=await action("users-list",{});assert.equal(JSON.stringify(list).includes("leaseToken"),false);
  const latest=list.body.users.find(u=>u.id===userId);
  assert.ok(latest.lifecycle);validate("IdentityUser",latest);
  const audit=await owner.query("SELECT 1 FROM brai_identity_audit WHERE target_id=$1 AND action='users-revoke'",[userId]);assert.ok(audit.rowCount>0);
  const permissions=(await app.query("SELECT has_table_privilege(current_user,'brai_user_operation','SELECT,INSERT,UPDATE,DELETE') AS queue,has_table_privilege(current_user,'brai_identity_audit','UPDATE') AS audit_update")).rows[0];
  assert.deepEqual(permissions,{queue:true,audit_update:false});
 }finally{
  if(userId)await owner.query('DELETE FROM "user" WHERE id=$1',[userId]);
  await owner.query('DELETE FROM "user" WHERE id=$1',[actor]);
  await app.end();await owner.end();
 }
});
